poeng = 0

#Jeg tror poeng blir: 10
poeng = poeng + 10
print (poeng)

#Jeg tror poeng blir 35
poeng += 25
print (poeng)

#Jeg tror poeng blir 30
poeng -= 5
print (poeng)

#Jeg tror poeng blir 60
poeng *= 2
print (poeng)

#Jeg tror poeng blir 15
poeng /= 4
print (poeng)

#Alle forutsigelsene mine stemte. 
#Datatypen "poeng" i det siste steget endret seg til en float, fordi summen ble delt. Da blir det alltid desimal uansett verdi.
#Utvidelsen ga samme resultat som +=, men ved å skrive += bruker man en snarvei som sparer tid, og holder oversikt. Det er mer ryddig å ha en fast rutine og en kjapp måte å skrive en variabel på.